// Build the shared app engine once, then serve it as static, unprivileged frame assets.
import { cp, access, writeFile, readFile, realpath, lstat, mkdtemp, rm } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, basename, resolve, sep } from 'node:path';
import { spawnSync } from 'node:child_process';
import { assertMatchingRuntime, runtimeIdentity, writeRuntimeManifest, checkRuntimeArtifact, installRuntimeArtifact } from './hosted-runtime-artifact.mjs';
const engine = process.env.SOFTN_REPO
  ? pathToFileURL(resolve(process.env.SOFTN_REPO) + sep)
  : new URL('../../../../softn.com/', import.meta.url);
const output = new URL('../public/hosted-runtime/', import.meta.url);
const npm = process.env.npm_execpath;
if (!npm) throw new Error('Run this script with npm run build:hosted-runtime.');
const source = runtimeIdentity(JSON.parse(await readFile(new URL('../vendor/zipp-wasm/SOURCE.json', import.meta.url), 'utf8')));
const hostedSource = runtimeIdentity(JSON.parse(await readFile(new URL('packages/@softn/core/wasm-zipp/SOURCE.json', engine), 'utf8')));
assertMatchingRuntime(hostedSource, source);
await access(new URL('node_modules/vite/bin/vite.js', engine));
const core = spawnSync(process.execPath, [npm, 'run', 'build', '-w', '@softn/core', '-w', '@softn/components'], { cwd: fileURLToPath(engine), stdio: 'inherit' });
if (core.status !== 0) process.exit(core.status || 1);
const built = spawnSync(process.execPath, [fileURLToPath(new URL('node_modules/vite/bin/vite.js', engine)), 'build', 'apps/formlogic-host', '--config', 'apps/formlogic-host/vite.config.ts'], { cwd: fileURLToPath(engine), stdio: 'inherit' });
if (built.status !== 0) process.exit(built.status || 1);
// Validate absolute targets before replacing only this generated directory.
const outputPath = fileURLToPath(output).replace(/[\\/]$/, '');
const publicPath = await realpath(new URL('../public/', import.meta.url));
if (dirname(outputPath) !== publicPath || basename(outputPath) !== 'hosted-runtime') throw new Error('Unexpected hosted runtime output directory.');
const previous = await lstat(outputPath).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
if (previous?.isSymbolicLink()) throw new Error('Refusing to replace a linked hosted runtime directory.');
const staged = await mkdtemp(resolve(publicPath, '.hosted-runtime-'));
if (dirname(staged) !== publicPath || !basename(staged).startsWith('.hosted-runtime-')) throw new Error('Unexpected runtime staging directory.');
try {
  await cp(new URL('apps/formlogic-host/dist/', engine), staged, {
    recursive: true,
    // Core worker assets include development source maps; release artifacts must not.
    filter: sourcePath => !sourcePath.endsWith('.map'),
  });
  await cp(new URL('LICENSE', engine), resolve(staged, 'LICENSE'));
  await cp(new URL('NOTICE', engine), resolve(staged, 'NOTICE'));
  await writeFile(resolve(staged, 'README.txt'), 'Generated by scripts/build-hosted-runtime.mjs from softn.com/apps/formlogic-host. Apache-2.0. Serve these static assets with Access-Control-Allow-Origin: * for the sandboxed app frame. The parent supplies matching ZIPP bytes through the private initialization channel. runtime-manifest.json verifies this complete build.\n');
  await writeRuntimeManifest(staged, hostedSource);
  await checkRuntimeArtifact(staged, source);
  await rm(outputPath, { recursive: true, force: true });
  await installRuntimeArtifact(staged, outputPath, source);
} finally {
  await rm(staged, { recursive: true, force: true });
}
console.log('Hosted app runtime built.');
