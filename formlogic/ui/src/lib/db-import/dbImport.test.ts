import { assertLoopbackBridgeUrl } from './localBridge';
import { SAMPLE_SCHEMAS, type MaterializedTable } from './types';

describe('Database Import — Multi-dialect SQL, Prisma, CSV/JSON & SQLite parser', () => {
  it('parses MySQL DDL + ENUMs + FKs + INSERT rows', () => {
    const preset = SAMPLE_SCHEMAS.find((s) => s.id === 'mysql-ecommerce')!;
    expect(detectSchemaDialect(preset.sql)).toBe('mysql');

    const schema = parseSqlSchema(preset.sql, 'auto', 'ecommerce.sql');
    expect(schema.dialect).toBe('mysql');
    expect(schema.tables.map((t) => t.name)).toEqual(['customers', 'categories', 'products', 'orders']);

    const customers = schema.tables.find((t) => t.name === 'customers')!;
    expect(customers.rows).toHaveLength(3);
    expect(customers.rows[0].full_name).toBe('Ada Lovelace');
    const tierCol = customers.columns.find((c) => c.name === 'tier')!;
    expect(tierCol.enumValues).toEqual(['Standard', 'Silver', 'Gold', 'VIP']);

    const orders = schema.tables.find((t) => t.name === 'orders')!;
    expect(orders.foreignKeys).toHaveLength(2);
    expect(orders.rows).toHaveLength(3);
    expect(orders.rows[2].notes).toBeNull();
  });

  it('parses PostgreSQL CREATE TYPE ENUM + self-FK + COPY ... FROM stdin', () => {
    const preset = SAMPLE_SCHEMAS.find((s) => s.id === 'postgres-crm')!;
    expect(detectSchemaDialect(preset.sql)).toBe('postgresql');

    const schema = parseSqlSchema(preset.sql, 'auto', 'crm.sql');
    expect(schema.dialect).toBe('postgresql');
    expect(schema.tables.map((t) => t.name)).toEqual(['accounts', 'team_members', 'deals']);

    const team = schema.tables.find((t) => t.name === 'team_members')!;
    expect(team.rows).toHaveLength(2);
    expect(team.rows[0].manager_id).toBeNull();
    expect(team.rows[1].manager_id).toBe('10');

    const deals = schema.tables.find((t) => t.name === 'deals')!;
    const stageCol = deals.columns.find((c) => c.name === 'stage')!;
    expect(stageCol.enumValues).toEqual(['Lead', 'Qualified', 'Proposal', 'Won', 'Lost']);
    expect(deals.rows).toHaveLength(2);
  });

  it('parses MSSQL T-SQL [dbo] brackets, IDENTITY, CHECK IN, GO, ALTER TABLE FKs, and N-strings', () => {
    const preset = SAMPLE_SCHEMAS.find((s) => s.id === 'mssql-helpdesk')!;
    expect(detectSchemaDialect(preset.sql)).toBe('mssql');

    const schema = parseSqlSchema(preset.sql, 'auto', 'helpdesk.sql');
    expect(schema.dialect).toBe('mssql');
    expect(schema.tables.map((t) => t.name)).toEqual(['Departments', 'Agents', 'Tickets']);

    const tickets = schema.tables.find((t) => t.name === 'Tickets')!;
    expect(tickets.foreignKeys.map((fk) => fk.targetTable)).toEqual(['Departments', 'Agents']);
    expect(tickets.columns.find((c) => c.name === 'Priority')?.enumValues).toEqual(['Low', 'Medium', 'High', 'Critical']);
    expect(tickets.rows).toHaveLength(2);
    expect(tickets.rows[0].Subject).toBe('VPN latency on Sydney gateway');
  });

  it('parses Oracle DDL (VARCHAR2, NUMBER, slash separator)', () => {
    const oracleSql = `
      CREATE TABLE ASSETS (
        ASSET_ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ASSET_NAME VARCHAR2(120) NOT NULL,
        COST NUMBER(12, 2),
        PURCHASE_DATE DATE
      )
      /
    `;
    const schema = parseSqlSchema(oracleSql, 'auto', 'assets.sql');
    expect(schema.dialect).toBe('oracle');
    expect(schema.tables).toHaveLength(1);
    expect(schema.tables[0].columns.map((c) => c.name)).toEqual(['ASSET_ID', 'ASSET_NAME', 'COST', 'PURCHASE_DATE']);
  });

  it('parses Prisma schemas with models, enums, and @relation foreign keys', () => {
    const prisma = `
      enum Priority {
        LOW
        HIGH
      }
      model Project {
        id Int @id @default(autoincrement())
        title String
        tasks Task[]
      }
      model Task {
        id Int @id @default(autoincrement())
        summary String
        priority Priority
        projectId Int
        project Project @relation(fields: [projectId], references: [id])
      }
    `;
    const schema = parseSqlSchema(prisma, 'auto', 'schema.prisma');
    expect(schema.dialect).toBe('prisma');
    expect(schema.tables.map((t) => t.name)).toEqual(['Project', 'Task']);
    const task = schema.tables[1];
    expect(task.foreignKeys[0]).toEqual({ column: 'projectId', targetTable: 'Project', targetColumn: 'id' });
    expect(task.columns.find((c) => c.name === 'priority')?.enumValues).toEqual(['LOW', 'HIGH']);
  });

  it('topologically sorts parents before children, detects self-FK cycles, and builds valid PackData', () => {
    const preset = SAMPLE_SCHEMAS.find((s) => s.id === 'postgres-crm')!;
    const schema = parseSqlSchema(preset.sql, 'auto');
    const mappings = buildInitialTableMappings(schema);

    const { order, cyclicLinks } = topologicalSortTables(mappings);
    const keys = order.map((t) => t.tableKey);
    expect(keys.indexOf('accounts')).toBeLessThan(keys.indexOf('deals'));
    expect(keys.indexOf('team_members')).toBeLessThan(keys.indexOf('deals'));
    expect(cyclicLinks).toEqual([
      { tableKey: 'team_members', fieldId: 'manager_id', targetTableKey: 'team_members' },
    ]);

    const pack = buildMigrationPack(mappings, {
      mode: 'new_app',
      appName: 'Migrated CRM',
      appDescription: '',
      includeDashboard: true,
      dialectLabel: 'PostgreSQL',
    });

    expect(pack.packMeta.id).toBe('custom');
    expect(pack.forms).toHaveLength(3);
    expect(pack.apps).toHaveLength(1);
    const dealsForm = pack.forms.find((f) => f.packFormId === 'deals')!;
    const dealsFields = (dealsForm.fields as Array<{ type: string; properties?: Record<string, unknown> }>) ?? [];
    const accountField = dealsFields.find((f) => f.type === 'linked_record' && f.properties?.targetFormId === '@pack:accounts');
    expect(accountField).toBeTruthy();

    // Prepare a child row and verify legacy PK -> FormLogic responseId remapping.
    const materializedDeals: MaterializedTable = {
      tableKey: 'deals',
      sourceName: 'deals',
      formId: 'form-deals',
      formTitle: 'Deals',
      primaryKeyColumn: 'id',
      fields: mappings.find((m) => m.tableKey === 'deals')!.fields,
      linkedFieldTargets: {
        account_id: { targetTableKey: 'accounts', targetFormId: 'form-accounts', allowMultiple: false },
        owner_id: { targetTableKey: 'team_members', targetFormId: 'form-team', allowMultiple: false },
      },
    };
    const pkMaps = new Map<string, Map<string, string>>([
      ['accounts', new Map([['1', 'resp-acc-1']])],
      ['team_members', new Map([['11', 'resp-tm-11']])],
    ]);
    const colMap: Record<string, string> = {};
    for (const f of materializedDeals.fields) if (f.include) colMap[f.sourceColumn] = f.fieldId;

    const prepared = prepareBatchImportRow(
      { id: 501, title: 'Fleet Rollout', account_id: 1, owner_id: 11, stage: 'Proposal', deal_value: '84000.00' },
      materializedDeals,
      colMap,
      'id',
      pkMaps,
      new Set(),
    );
    expect(prepared.clientKey).toBe('501');
    expect(prepared.answers.account_id).toBe('resp-acc-1');
    expect(prepared.answers.owner_id).toBe('resp-tm-11');
    expect(prepared.answers.deal_value).toBe(84000);
  });

  it('parses RFC 4180 CSV with quoted newlines and JSON/NDJSON cleanly', () => {
    const csv = 'id,name,notes\n1,"Ada","Line 1\nLine ""2"""\n2,"Grace","Hello"\n';
    const parsedCsv = parseDelimitedText(csv);
    expect(parsedCsv.headers).toEqual(['id', 'name', 'notes']);
    expect(parsedCsv.rows).toHaveLength(2);
    expect(parsedCsv.rows[0].notes).toBe('Line 1\nLine "2"');

    const ndjson = '{"id":1,"name":"A"}\n{"id":2,"name":"B"}\n';
    const parsedJson = parseJsonDataText(ndjson);
    expect(parsedJson.format).toBe('ndjson');
    expect(parsedJson.rows).toHaveLength(2);
  });

  it('reads a real SQLite 3 binary file in pure TypeScript without WASM', () => {
    // Generate a real SQLite3 file via PHP PDO if php is on PATH (available in local & CI).
    const tmpFile = join(tmpdir(), `fl-sqlite-reader-test-${Date.now()}.sqlite`);
    try {
      execFileSync('php', [
        '-r',
        `$db = new PDO('sqlite:' . $argv[1]);
         $db->exec('CREATE TABLE users (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, score REAL, active INTEGER);');
         $db->exec("INSERT INTO users (name, score, active) VALUES ('Ada', 98.5, 1), ('Alan', 99.25, 0);");`,
        tmpFile,
      ]);
    } catch {
      // Skip binary generation if php CLI is unavailable in an isolated JS-only environment.
      return;
    }

    try {
      const bytes = new Uint8Array(readFileSync(tmpFile));
      expect(isSqliteBinary(bytes)).toBe(true);
      const read = readSqliteFile(bytes);
      expect(read.tables).toHaveLength(1);
      expect(read.tables[0].name).toBe('users');
      expect(read.tables[0].rows).toEqual([
        { id: 1, name: 'Ada', score: 98.5, active: 1 },
        { id: 2, name: 'Alan', score: 99.25, active: 0 },
      ]);
    } finally {
      try { rmSync(tmpFile, { force: true }); } catch { /* ignore */ }
    }
  });

  it('enforces strictly loopback URLs on the local database bridge', () => {
    expect(assertLoopbackBridgeUrl('http://127.0.0.1:17985/')).toBe('http://127.0.0.1:17985');
    expect(assertLoopbackBridgeUrl('http://localhost:17985')).toBe('http://localhost:17985');
    expect(() => assertLoopbackBridgeUrl('https://evil.example.com:17985')).toThrow(/local-only/i);
    expect(() => assertLoopbackBridgeUrl('http://192.168.1.50:17985')).toThrow(/local-only/i);
  });

  it('auto-matches implicit foreign keys with PK type compatibility, picks rich select labels, and keeps boolean checkboxes optional', () => {
    const miningSql = `
      CREATE TABLE _phinxlog (version BIGINT PRIMARY KEY, migration_name VARCHAR(100));
      CREATE TABLE equipment_types (
        id INT PRIMARY KEY AUTO_INCREMENT,
        name VARCHAR(64) NOT NULL,
        category ENUM('truck','excavator','auxiliary') NOT NULL
      );
      CREATE TABLE locations (
        id VARCHAR(32) PRIMARY KEY,
        name VARCHAR(64) NOT NULL
      );
      CREATE TABLE reason_codes (
        id INT PRIMARY KEY AUTO_INCREMENT,
        code VARCHAR(32) NOT NULL,
        name VARCHAR(128) NOT NULL
      );
      CREATE TABLE users (
        id INT PRIMARY KEY AUTO_INCREMENT,
        username VARCHAR(64) NOT NULL,
        display_name VARCHAR(128) NOT NULL
      );
      CREATE TABLE shifts (
        id INT PRIMARY KEY,
        shift_date DATE NOT NULL,
        shift_name VARCHAR(16) NOT NULL,
        is_live TINYINT(1) NOT NULL DEFAULT 0
      );
      CREATE TABLE equipment (
        id VARCHAR(32) PRIMARY KEY,
        equipment_type_id INT NOT NULL,
        reason_code_id INT NULL,
        current_location_id VARCHAR(32) NULL,
        destination_location_id VARCHAR(32) NULL,
        operator_id VARCHAR(32) NULL,
        operator_name VARCHAR(64) NULL
      );
      CREATE TABLE shift_loads (
        id INT PRIMARY KEY AUTO_INCREMENT,
        shift_id INT NOT NULL,
        truck_id VARCHAR(32) NOT NULL,
        excavator_id VARCHAR(32) NOT NULL,
        tonnes FLOAT NOT NULL
      );
    `;

    const schema = parseSqlSchema(miningSql, 'mysql', 'mine_management.sql');
    const mappings = buildInitialTableMappings(schema);

    // System/migration table auto-excluded
    expect(isSystemOrMigrationTable('_phinxlog')).toBe(true);
    expect(mappings.find((m) => m.sourceName === '_phinxlog')?.include).toBe(false);

    // Boolean TINYINT(1) NOT NULL defaults to required: false so unchecked `false`/`0` saves cleanly
    const shifts = mappings.find((m) => m.tableKey === 'shifts')!;
    const isLiveField = shifts.fields.find((f) => f.sourceColumn === 'is_live')!;
    expect(isLiveField.fieldType).toBe('checkboxes');
    expect(isLiveField.required).toBe(false);
    expect(shifts.displayFieldIds).toEqual(['shift_date', 'shift_name']);

    // Smart code + name label pair on reason_codes
    const reasonCodes = mappings.find((m) => m.tableKey === 'reason_codes')!;
    expect(reasonCodes.displayFieldIds).toEqual(['code', 'name']);

    // Equipment has natural string PK `id` and NO dedicated `name` -> uses `id`, NOT `operator_name`!
    const equipment = mappings.find((m) => m.tableKey === 'equipment')!;
    expect(equipment.displayFieldIds).toEqual(['id']);
    expect(equipment.fields.find((f) => f.sourceColumn === 'equipment_type_id')?.targetTableKey).toBe('equipment_types');
    expect(equipment.fields.find((f) => f.sourceColumn === 'reason_code_id')?.targetTableKey).toBe('reason_codes');
    expect(equipment.fields.find((f) => f.sourceColumn === 'current_location_id')?.targetTableKey).toBe('locations');
    expect(equipment.fields.find((f) => f.sourceColumn === 'destination_location_id')?.targetTableKey).toBe('locations');
    expect(equipment.fields.find((f) => f.sourceColumn === 'equipment_type_id')?.fkSource).toBe('inferred');

    // Type-safety guard: equipment.operator_id (VARCHAR) must NOT falsely link to users.id (INT)!
    const opField = equipment.fields.find((f) => f.sourceColumn === 'operator_id')!;
    expect(opField.fieldType).toBe('short_text');
    expect(opField.targetTableKey).toBeUndefined();

    // Role aliases: truck_id and excavator_id (VARCHAR) match equipment (VARCHAR PK)!
    const shiftLoads = mappings.find((m) => m.tableKey === 'shift_loads')!;
    expect(shiftLoads.fields.find((f) => f.sourceColumn === 'shift_id')?.targetTableKey).toBe('shifts');
    expect(shiftLoads.fields.find((f) => f.sourceColumn === 'truck_id')?.targetTableKey).toBe('equipment');
    expect(shiftLoads.fields.find((f) => f.sourceColumn === 'excavator_id')?.targetTableKey).toBe('equipment');

    // Dependency closure pulls in shifts, equipment, equipment_types, reason_codes, locations from shift_loads alone
    const closure = expandRelatedTableKeys(mappings, new Set(['shift_loads']));
    expect(Array.from(closure).sort()).toEqual([
      'equipment',
      'equipment_types',
      'locations',
      'reason_codes',
      'shift_loads',
      'shifts',
    ]);

    // Generated pack wires displayFieldIds, searchFieldIds, placeholder, and relatedAllowAdd
    const pack = buildMigrationPack(mappings, {
      mode: 'new_app',
      appName: 'Mine Management CRUD',
      appDescription: '',
      includeDashboard: true,
      dialectLabel: 'MySQL',
    });
    const shiftLoadsForm = pack.forms.find((f) => f.packFormId === 'shift_loads')!;
    const shiftLoadsFields = shiftLoadsForm.fields as Array<{ id: string; type: string; placeholder?: string; properties?: Record<string, unknown> }>;
    const truckField = shiftLoadsFields.find((f) => f.id === 'truck_id')!;
    expect(truckField.type).toBe('linked_record');
    expect(truckField.placeholder).toBe('Select Equipment...');
    expect(truckField.properties?.targetFormId).toBe('@pack:equipment');
    expect(truckField.properties?.displayFieldIds).toEqual(['id']);
    expect(truckField.properties?.relatedAllowAdd).toBe(true);

    // Generated dashboard widgets and reports match PackReportSpec / PackDashboardWidget contract
    const app = (pack.apps?.[0] ?? {}) as {
      customScreen?: { enabled?: boolean; kind?: string; dashboard?: { widgets: Array<Record<string, unknown>> } };
      reports?: Array<Record<string, unknown>>;
    };
    expect(app.customScreen?.enabled).toBe(true);
    expect(app.customScreen?.kind).toBe('dashboard');
    const widgets = app.customScreen?.dashboard?.widgets ?? [];
    const kpiWidget = widgets.find((w) => String(w.id).startsWith('kpi_'))!;
    expect((kpiWidget.spec as Record<string, unknown>)?.viz).toBe('kpi');
    expect((kpiWidget.spec as Record<string, unknown>)?.measure).toEqual({ fn: 'count' });
    const chartWidget = widgets.find((w) => String(w.id).startsWith('chart_'))!;
    expect((chartWidget.spec as Record<string, unknown>)?.viz).toBe('bar');
    expect((chartWidget.spec as Record<string, unknown>)?.measure).toEqual({ fn: 'count' });
    const listWidget = widgets.find((w) => String(w.id).startsWith('list_'))!;
    expect((listWidget.list as Record<string, unknown>)?.titleField).toBeTruthy();
    expect(app.reports?.[0]?.kind).toBe('chart');
    expect(app.reports?.[0]?.reportId).toBeTruthy();
  });

  it('parses SSMS bracketed MSSQL types, PRIMARY KEY NONCLUSTERED WITH (...), and ALTER TABLE CHECK', () => {
    const ssmsSql = `
      USE [ITCOperational]
      GO
      SET ANSI_NULLS ON
      GO
      CREATE TABLE [ApplicationConfiguration].[Configuration](
        [Id] [numeric](10, 0) IDENTITY(1,1) NOT NULL,
        [Scope] [nvarchar](128) NOT NULL,
        [Status] [nvarchar](32) NOT NULL,
        [Value] [ntext] NULL,
        [Timestamp] [datetime] NOT NULL,
        CONSTRAINT [PK_CONFIGURATION] PRIMARY KEY NONCLUSTERED ([Id] ASC)
        WITH (PAD_INDEX = OFF, ALLOW_ROW_LOCKS = ON) ON [PRIMARY]
      ) ON [PRIMARY] TEXTIMAGE_ON [PRIMARY]
      GO
      ALTER TABLE [ApplicationConfiguration].[Configuration] WITH CHECK ADD CONSTRAINT [CK_Status]
        CHECK ([Status] IN ('Active', 'Disabled', 'Pending'))
      GO
    `;
    expect(detectSchemaDialect(ssmsSql)).toBe('mssql');
    const schema = parseSqlSchema(ssmsSql, 'auto', 'itc.sql');
    expect(schema.dialect).toBe('mssql');
    expect(schema.tables).toHaveLength(1);
    const tbl = schema.tables[0];
    expect(tbl.schemaName).toBe('ApplicationConfiguration');
    expect(tbl.primaryKeys).toEqual(['Id']);
    expect(tbl.columns.find((c) => c.name === 'Id')?.isAutoIncrement).toBe(true);
    expect(tbl.columns.find((c) => c.name === 'Status')?.enumValues).toEqual(['Active', 'Disabled', 'Pending']);
    expect(tbl.columns.find((c) => c.name === 'Value')?.normalizedType).toBe('ntext');
  });

  it('normalizes datetime, time, and Buffer-encoded booleans during batch row preparation', () => {
    const tbl: MaterializedTable = {
      tableKey: 'events',
      sourceName: 'events',
      formId: 'f1',
      formTitle: 'Events',
      primaryKeyColumn: 'id',
      fields: [
        { sourceColumn: 'occurred_at', fieldId: 'occurred_at', label: 'Occurred At', rawType: 'datetime', fieldType: 'datetime', include: true, required: false, isPrimaryKey: false, isAutoIncrement: false },
        { sourceColumn: 'start_time', fieldId: 'start_time', label: 'Start Time', rawType: 'time', fieldType: 'time', include: true, required: false, isPrimaryKey: false, isAutoIncrement: false },
        { sourceColumn: 'is_active', fieldId: 'is_active', label: 'Is Active', rawType: 'bit', fieldType: 'checkboxes', include: true, required: false, isPrimaryKey: false, isAutoIncrement: false },
      ],
      linkedFieldTargets: {},
    };
    const res = prepareBatchImportRow(
      {
        id: 7,
        occurred_at: '2026-04-19T12:35:00.000Z',
        start_time: '06:30:00',
        is_active: { type: 'Buffer', data: [1] },
      },
      tbl,
      { occurred_at: 'occurred_at', start_time: 'start_time', is_active: 'is_active' },
      'id',
      new Map(),
      new Set(),
    );
    expect(res.clientKey).toBe('7');
    expect(res.answers.occurred_at).toBe('2026-04-19T12:35');
    expect(res.answers.start_time).toBe('06:30');
    expect(res.answers.is_active).toBe('1');
  });
});
