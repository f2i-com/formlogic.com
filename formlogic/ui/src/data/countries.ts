export const COUNTRY_BY_ISO: Record<string, CountryData> = {};
for (const c of COUNTRIES) {
  COUNTRY_BY_ISO[c.iso] = c;
}

// Map dial code -> array of countries (first entry is "primary")
export const COUNTRIES_BY_DIAL_CODE: Record<string, CountryData[]> = {};
for (const c of COUNTRIES) {
  const code = c.dialCode;
  if (!COUNTRIES_BY_DIAL_CODE[code]) {
    COUNTRIES_BY_DIAL_CODE[code] = [];
  }
  COUNTRIES_BY_DIAL_CODE[code].push(c);
}

// For +1 ensure US is first
if (COUNTRIES_BY_DIAL_CODE['+1']) {
  const usIdx = COUNTRIES_BY_DIAL_CODE['+1'].findIndex(c => c.iso === 'US');
  if (usIdx > 0) {
    const [us] = COUNTRIES_BY_DIAL_CODE['+1'].splice(usIdx, 1);
    COUNTRIES_BY_DIAL_CODE['+1'].unshift(us);
  }
}

// For +7 ensure RU is first
if (COUNTRIES_BY_DIAL_CODE['+7']) {
  const ruIdx = COUNTRIES_BY_DIAL_CODE['+7'].findIndex(c => c.iso === 'RU');
  if (ruIdx > 0) {
    const [ru] = COUNTRIES_BY_DIAL_CODE['+7'].splice(ruIdx, 1);
    COUNTRIES_BY_DIAL_CODE['+7'].unshift(ru);
  }
}
