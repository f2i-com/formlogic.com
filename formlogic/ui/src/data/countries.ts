export interface CountryData {
  iso: string;
  name: string;
  dialCode: string;
  flag: string;
}

function isoToFlag(iso: string): string {
  return [...iso.toUpperCase()].map(c => String.fromCodePoint(0x1F1E6 + c.charCodeAt(0) - 65)).join('');
}

function mkc(iso: string, name: string, dialCode: string): CountryData {
  return { iso, name, dialCode, flag: isoToFlag(iso) };
}

