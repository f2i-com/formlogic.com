// Compile text with the same offline JSX/SFC modules as Studio. Guest source is an argument
// to the parser. Only checked editor modules can be loaded into the compiler context.
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const deploy = fileURLToPath(new URL('../../', import.meta.url));
const editor = ['app-editors/studio', 'ui/dist/app-editors/studio', 'ui/public/app-editors/studio']
  .map(folder => join(deploy, folder)).find(folder => existsSync(join(folder, 'runtime-manifest.json')));
const unavailable = 'The installed Studio source compiler is unavailable. Install the matching app editors or save the component in Studio or Builder.';

async function run() {
  if (!editor) throw new Error(unavailable);
  const { files: checksums } = JSON.parse(await readFile(join(editor, 'runtime-manifest.json'), 'utf8'));
  async function checked(path) {
    const data = await readFile(join(editor, path));
    if (createHash('sha256').update(data).digest('hex') !== checksums[path]) throw new Error(unavailable);
    return data.toString('utf8');
  }
  const manifest = JSON.parse(await checked('.vite/manifest.json'));
  const context = vm.createContext({}, { codeGeneration: { strings: false, wasm: false } });
  const loaded = new Map();
  async function load(path) {
    if (!/^assets\/[A-Za-z0-9_.-]+\.js$/.test(path) || !checksums[path]) throw new Error(unavailable);
    if (!loaded.has(path)) {
      loaded.set(path, checked(path).then(code => new vm.SourceTextModule(code, { context, identifier: path })));
    }
    return loaded.get(path);
  }
  const compiled = {};
  const parsers = new Map();
  const input = JSON.parse(await readFile(process.argv[2], 'utf8'));
  for (const [path, source] of Object.entries(input)) {
    const format = /\.jsx$/i.test(path) ? 'jsx' : 'vue';
    if (!parsers.has(format)) {
      const suffix = '/editor-shared/src/sourceCompilers/' + format + '.ts';
      const entry = Object.entries(manifest).find(([key]) => key.endsWith(suffix))?.[1];
      if (!entry?.file) throw new Error(unavailable);
      const module = await load(entry.file);
      await module.link((specifier, from) => {
        if (!/^\.\/[A-Za-z0-9_.-]+\.js$/.test(specifier)) throw new Error(unavailable);
        return load(dirname(from.identifier) + '/' + specifier.slice(2));
      });
      await module.evaluate();
      if (typeof module.namespace.compile !== 'function') throw new Error(unavailable);
      parsers.set(format, module.namespace.compile);
    }
    try {
      const code = parsers.get(format)(source, path);
      const digest = createHash('sha256').update(path + '\0' + source.replace(/^\uFEFF/, '')).digest('hex');
      const result = '// Generated by SoftN from component source.\n// SoftN source SHA-256: ' + digest + '\n' + code;
      if (Buffer.byteLength(result) > 1500000) throw new Error('The compiled module exceeds 1.5 MB.');
      compiled[path] = result;
    } catch (error) {
      throw new Error(path + ': ' + (error.message || 'The component could not be compiled.').slice(0, 800));
    }
  }
  return { compiled };
}

try {
  process.stdout.write(JSON.stringify(await run()));
} catch (error) {
  process.stdout.write(JSON.stringify({ error: (error.message || unavailable).slice(0, 1100) }));
  process.exitCode = 1;
}
